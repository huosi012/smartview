def z_floor(y):
    """坑底跨内顶面标高（横坡1%）。"""
    return Z_CAP - CROWN * min(abs(y), B_HALF) / B_HALF


def z_gutter(x):
    """排水沟沟底标高（沿 X 的近似）。"""
    z0 = z_floor(GUT_Y[0]) - GUT_DEPTH0
    if x <= AX[2]:
        return z0 - GUT_I * (x - GUT_START)
    return z0 - GUT_I * ((L - GUT_START) - x)


def gutter_lines(side=1):
    """排水沟平面边线。沟宽150，沿侧墙内侧布置；过②、④墩时经检修口内绕开传感器水泥台，
    终于③轴两侧检修口内的集水坑。返回 [内边线, 外边线, 起端封口线] × 左右两半。"""
    s = side
    yi, yw, yj = GUT_Y[0], GUT_Y[1], 1750
    res = []
    for mirror in (False, True):
        xa = AX[1]
        inner = [(GUT_START, yi), (xa - 260, yi), (xa - 260, yw), (xa + 260, yw),
                 (xa + 260, yi), (AX[2] - 260, yi), (AX[2] - 260, yw), (SUMP[0], yw)]
        outer = [(GUT_START, yw), (xa - 400, yw), (xa - 400, yj), (xa + 400, yj),
                 (xa + 400, yw), (AX[2] - 400, yw), (AX[2] - 400, yj), (SUMP[0], yj)]
        cap = [(GUT_START, yi), (GUT_START, yw)]
        for pts in (inner, outer, cap):
            if mirror:
                pts = [(L - x, y) for x, y in pts]
            res.append([(x, s * y) for x, y in pts])
    return res


