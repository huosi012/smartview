def quantities():
    raft = (X_RIGHT - X_LEFT) * 3600 * 300
    beams = 0.0
    for x1, x2, nm in BEAMS:
        w = x2 - x1
        beams += w * 4700 * 800 - w * 3600 * 300
    q1 = Q1_LEN * 200 * 500
    q2 = 2 * (4700 * 500 * 500 - 3600 * 200 * 250)
    sump = 2 * 400 * 400 * 400
    c35 = (raft + beams + q1 + q2 - sump) / 1e9
    yb = 2 * (APP[0][1] - APP[0][0]) * 3600 * APP_T / 1e9
    cush = ((X_RIGHT - X_LEFT + 200) * 3800 + 6800 * 1100) * T_CUSH / 1e9
    _, tot = bar_rows()
    steel = sum(tot.values()) / 1000.0
    return c35, yb, cush, steel


