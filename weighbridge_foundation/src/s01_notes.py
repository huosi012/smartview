def write_col(p, x, y, sections, width_chars, h=4.6, gap=1.75):
    step = h * gap
    for title, items in sections:
        p.text(x, y, title, h * 1.25, "TL")
        y -= step * 1.35
        for i, s in enumerate(items, 1):
            y = p.para(x + 2, y, f"{i}. {s}", width_chars, h, gap, hang=2)
        y -= step * 0.4
    return y


